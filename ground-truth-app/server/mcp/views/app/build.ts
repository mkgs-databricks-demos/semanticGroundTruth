// server/mcp/views/app/build.ts — bundles the review card MCP App into one self-contained HTML string
// Session 34 · Wave 4-2 · No enum, no namespace, no default export
//
// Regenerate after changing view.ts / main.ts / entry.ts / template.ts:
//   pnpm exec tsx server/mcp/views/app/build.ts
// It writes reviewCardApp.generated.ts (committed). build.test.ts rebuilds in
// memory and fails when the committed module is stale. Uses the app's own
// Vite (rolldown-vite) in library mode: one IIFE chunk, inlined into the HTML.

import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { gzipSync } from 'node:zlib';
import { build } from 'vite';
import { renderReviewCardAppHtml } from './template';

const HERE = path.dirname(fileURLToPath(import.meta.url));

export const GENERATED_FILE = path.join(HERE, 'reviewCardApp.generated.ts');

// Size budget. Design L300-17 §2 targets < 100 KB, assuming the ext-apps App
// client is ~30 KB. main.ts imports the lean entry (dist/src/app.js, 33 KB), and
// this build bundles its peers: the MCP SDK protocol + types (~28 KB) and zod,
// which the SDK v1 needs at runtime to validate every message. zod is most of
// the card, so the 100 KB target is applied to the gzipped document (what
// crosses the wire, ~75 KB on zod 4.6.7 with the locale trim below) and the raw
// document gets a ceiling that catches accidental growth.
// SDK v2 (2026-10-30): ext-apps 2.0.4 builds App on @modelcontextprotocol/client
// 2.4.0 (protocol + 2026-07-28 schemas, incl. OAuth metadata schemas that do not
// tree-shake). Card: 318,695 bytes raw, 83,783 gzip (was 273,447 / 75,467 on v1).
export const HTML_GZIP_BUDGET_BYTES = 100 * 1024;
export const HTML_RAW_CEILING_BYTES = 400 * 1024;

export interface HtmlSize {
  raw: number;
  gzip: number;
}

export function measureHtml(html: string): HtmlSize {
  return { raw: Buffer.byteLength(html, 'utf8'), gzip: gzipSync(html).length };
}

/** Throws when the document is over budget. */
export function assertHtmlBudget(html: string): HtmlSize {
  const size = measureHtml(html);
  if (size.gzip > HTML_GZIP_BUDGET_BYTES || size.raw > HTML_RAW_CEILING_BYTES) {
    throw new Error(
      `review card HTML is ${size.raw} bytes (${size.gzip} gzipped); budget is ` +
        `${HTML_GZIP_BUDGET_BYTES} gzipped and ${HTML_RAW_CEILING_BYTES} raw`,
    );
  }
  return size;
}

// zod's classic and mini entry points re-export every locale (`export * as
// locales`). The ext-apps / MCP SDK namespace imports keep all 51 of them in the
// bundle (colinhacks/zod#6050): ~185 KB minified of translated error messages
// the card never shows. Keep only English, which zod registers as the default.
// 2026-10-29 trial: card 113,476 -> 75,467 bytes gzip on zod 4.6.7; English
// messages still produced at runtime by classic zod and zod mini.
const ZOD_LOCALES_INDEX = /[\\/]zod[\\/]v4[\\/]locales[\\/]index\.js$/;
export const zodEnglishOnlyLocales = {
  name: 'zod-english-only-locales',
  enforce: 'pre' as const,
  load(id: string): string | null {
    return ZOD_LOCALES_INDEX.test(id) ? 'export { default as en } from "./en.js";\n' : null;
  },
};

/** Bundle entry.ts (and everything it imports) into one minified IIFE. */
export async function bundleReviewCardScript(): Promise<string> {
  const out = await build({
    configFile: false,
    logLevel: 'silent',
    mode: 'production',
    root: HERE,
    publicDir: false,
    plugins: [zodEnglishOnlyLocales],
    define: { 'process.env.NODE_ENV': JSON.stringify('production') },
    build: {
      write: false,
      minify: true,
      sourcemap: false,
      target: 'es2020',
      emptyOutDir: false,
      copyPublicDir: false,
      reportCompressedSize: false,
      lib: {
        entry: path.join(HERE, 'entry.ts'),
        formats: ['iife'],
        name: 'GroundTruthReviewCard',
        fileName: () => 'review-card.js',
      },
    },
  });
  const outputs = Array.isArray(out) ? out : [out];
  for (const o of outputs) {
    if (!('output' in o)) continue;
    for (const chunk of o.output) {
      if (chunk.type === 'chunk') return chunk.code.trim();
    }
  }
  throw new Error('vite build produced no JS chunk for the review card');
}

/** The full HTML document served for ui://ground-truth/review-card. */
export async function buildReviewCardHtml(): Promise<string> {
  return renderReviewCardAppHtml(await bundleReviewCardScript());
}

/** Source text of reviewCardApp.generated.ts for a given HTML document. */
export function renderGeneratedModule(html: string): string {
  return [
    '// server/mcp/views/app/reviewCardApp.generated.ts — GENERATED by build.ts, do not edit',
    '// Regenerate: pnpm exec tsx server/mcp/views/app/build.ts (build.test.ts fails when stale)',
    '',
    'export const REVIEW_CARD_APP_HTML: string =',
    `  ${JSON.stringify(html)};`,
    '',
  ].join('\n');
}

async function main(): Promise<void> {
  const html = await buildReviewCardHtml();
  const size = assertHtmlBudget(html);
  await writeFile(GENERATED_FILE, renderGeneratedModule(html), 'utf8');
  console.log(`wrote ${path.relative(process.cwd(), GENERATED_FILE)} (${size.raw} bytes, ${size.gzip} gzipped)`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((err: unknown) => {
    console.error(err);
    process.exitCode = 1;
  });
}
